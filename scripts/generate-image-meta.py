"""Generate data/image-meta.ts (dimensions + blur placeholders) from public/images."""
import base64, io, pathlib
from PIL import Image

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "public" / "images"
lines = ["// Generated by scripts/generate-image-meta.py. Do not edit by hand.", "", "export const imageMeta = {"]
for path in sorted(src.iterdir()):
    if path.suffix not in {".png", ".webp", ".jpg"}:
        continue
    im = Image.open(path)
    w, h = im.size
    thumb = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
    thumb.thumbnail((16, 16))
    buf = io.BytesIO()
    thumb.save(buf, "WEBP", quality=40)
    blur = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()
    lines.append(f'  "{path.name}": {{ width: {w}, height: {h}, blurDataURL: "{blur}" }},')
lines += ["} as const;", "", "export type ImageFile = keyof typeof imageMeta;", ""]
(root / "data" / "image-meta.ts").write_text("\n".join(lines))
print("wrote", len(lines) - 5, "entries")
